do $$
declare
  imported_count integer;
  review_count integer;
begin
  select count(*), count(*) filter (where needs_review)
  into imported_count, review_count
  from public.teams
  where source_label ~ '^(ESF|EMULTI|ESB|EAPP|ECR) [0-9]{3} ';

  if imported_count <> 176 then
    raise exception 'TEAM_CATALOG_COUNT_MISMATCH: expected 176, got %', imported_count;
  end if;
  if review_count <> 2 then
    raise exception 'TEAM_CATALOG_REVIEW_COUNT_MISMATCH: expected 2, got %', review_count;
  end if;
end
$$;

